-- Fresh SYNAX schema for Cloudflare D1.
-- This migration creates only the two-person application's own database.

CREATE TABLE IF NOT EXISTS synax_state (
  id TEXT PRIMARY KEY,
  state TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS synax_sessions (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL CHECK (user_id IN ('person_1', 'person_2', 'admin')),
  session_start INTEGER NOT NULL,
  last_active INTEGER NOT NULL,
  allowed_seconds INTEGER NOT NULL,
  is_expired INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 0,
  ended_at INTEGER
);
CREATE INDEX IF NOT EXISTS synax_sessions_user_id_idx ON synax_sessions(user_id);
CREATE INDEX IF NOT EXISTS synax_sessions_session_start_idx ON synax_sessions(session_start DESC);

CREATE TABLE IF NOT EXISTS synax_messages (
  id TEXT PRIMARY KEY,
  client_message_id TEXT UNIQUE,
  sender_id TEXT NOT NULL CHECK (sender_id IN ('person_1', 'person_2', 'system')),
  type TEXT NOT NULL CHECK (type IN ('text', 'image', 'video', 'file', 'voice', 'system')),
  text TEXT NOT NULL DEFAULT '',
  file_url TEXT,
  file_name TEXT,
  file_size INTEGER,
  audio_duration REAL,
  timestamp INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'sent' CHECK (status IN ('sent', 'delivered', 'read')),
  reactions TEXT NOT NULL DEFAULT '{}',
  reply_to TEXT,
  is_pinned INTEGER NOT NULL DEFAULT 0,
  is_edited INTEGER NOT NULL DEFAULT 0,
  deleted INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS synax_messages_timestamp_idx ON synax_messages(timestamp DESC, id DESC);
CREATE INDEX IF NOT EXISTS synax_messages_sender_status_idx ON synax_messages(sender_id, status);
CREATE INDEX IF NOT EXISTS synax_messages_client_message_id_idx ON synax_messages(client_message_id);

CREATE TABLE IF NOT EXISTS synax_user_usage (
  user_id TEXT PRIMARY KEY CHECK (user_id IN ('person_1', 'person_2')),
  continuous_used_seconds INTEGER NOT NULL DEFAULT 0,
  daily_used_seconds INTEGER NOT NULL DEFAULT 0,
  daily_usage_date TEXT,
  active INTEGER NOT NULL DEFAULT 0,
  active_started_at INTEGER,
  last_heartbeat INTEGER NOT NULL DEFAULT 0,
  last_seen INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT,
  usage_version INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS synax_chat_settings (
  chat_id TEXT PRIMARY KEY,
  background_type TEXT NOT NULL DEFAULT 'preset',
  background_value TEXT NOT NULL DEFAULT 'stars',
  background_updated_at INTEGER NOT NULL DEFAULT 0,
  updated_by TEXT,
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS synax_call_signals (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  from_user_id TEXT NOT NULL CHECK (from_user_id IN ('person_1', 'person_2')),
  target_user_id TEXT NOT NULL CHECK (target_user_id IN ('person_1', 'person_2')),
  type TEXT NOT NULL,
  call_type TEXT NOT NULL CHECK (call_type IN ('voice', 'video')),
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS synax_call_signals_target_id_idx ON synax_call_signals(target_user_id, id);
CREATE INDEX IF NOT EXISTS synax_call_signals_created_at_idx ON synax_call_signals(created_at);

-- Multipart upload bookkeeping. File bytes live in R2, never in D1.
CREATE TABLE IF NOT EXISTS synax_uploads (
  upload_id TEXT PRIMARY KEY,
  object_key TEXT NOT NULL UNIQUE,
  r2_upload_id TEXT NOT NULL,
  user_id TEXT NOT NULL CHECK (user_id IN ('person_1', 'person_2')),
  file_name TEXT NOT NULL,
  content_type TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  uploaded_size INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL,
  completed INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS synax_uploads_user_id_idx ON synax_uploads(user_id, created_at);

CREATE TABLE IF NOT EXISTS synax_upload_parts (
  upload_id TEXT NOT NULL,
  part_number INTEGER NOT NULL,
  etag TEXT NOT NULL,
  part_size INTEGER NOT NULL,
  PRIMARY KEY (upload_id, part_number),
  FOREIGN KEY (upload_id) REFERENCES synax_uploads(upload_id) ON DELETE CASCADE
);


-- Small per-account + per-IP login throttle. IP addresses are not stored; the
-- primary key is an HMAC generated by the Worker using its private signing secret.
CREATE TABLE IF NOT EXISTS synax_login_attempts (
  attempt_key TEXT PRIMARY KEY,
  window_started_at INTEGER NOT NULL,
  failure_count INTEGER NOT NULL DEFAULT 0,
  locked_until INTEGER,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS synax_login_attempts_locked_until_idx ON synax_login_attempts(locked_until);
CREATE INDEX IF NOT EXISTS synax_login_attempts_updated_at_idx ON synax_login_attempts(updated_at);
